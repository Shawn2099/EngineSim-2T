function T = blair_validate(casepath, verbose)
%BLAIR_VALIDATE  Run the QUB 400 reference case and compare with Blair Fig.5.9.
%
%   T = BLAIR_VALIDATE()            the reference deck, prints the comparison
%   T = BLAIR_VALIDATE(CASEPATH)    another deck in the same format
%   T = BLAIR_VALIDATE(..., false)  no printing
%
%   Prints the model values beside the published ones and the ratio. The
%   published set is Fig.5.9 of Blair, The Basic Design of Two-Stroke Engines
%   (SAE): 3000 rpm, full throttle, SCRE, fifth cycle - the same cycle
%   BLAIR_RUN reports, so the two are directly comparable.
%
%   This is a printer, not a judge: the scored verdict comes from
%   sim/blair/check_qub400.m via run_qub400.m.
%
% See also BLAIR_INIT, BLAIR_RUN, RUN_QUB400, CHECK_QUB400.

if nargin < 1 || isempty(casepath)
    casepath = 'C:\Users\malliath\Desktop\engine_sim\port\QUB400_INPUT.dat';
end
if nargin < 2
    verbose = true;
end

mdl = blair_run(blair_init(casepath), 3000, 1.0);
r = mdl.results;

% quantity, model, published, unit
rows = { ...
    'Power',                r.power_kW,   12.2,   'kW'; ...
    'BMEP',                 r.bmep_bar,    6.14,  'bar'; ...
    'IMEP',                 r.imep_bar,    6.72,  'bar'; ...
    'PMEP',                 r.pmep_bar,    0.38,  'bar'; ...
    'FMEP',                 r.fmep_bar,    0.21,  'bar'; ...
    'BSFC',                 r.bsfc_gkWh, 464,     'g/kWh'; ...
    'Delivery ratio',       r.DR,          0.854, '-'; ...
    'Scavenging eff.',      r.SE,          0.818, '-'; ...
    'Trapping eff.',        r.TE,          0.504, '-'; ...
    'Charging eff.',        r.CE,          0.430, '-'; ...
    'Scav. ratio (mass)',   r.sr,          0.874, '-'; ...
    'Scav. ratio (vol)',    r.srv,         1.134, '-'; ...
    'Exhaust flow ratio',   r.exhaust_flow_ratio, 0.876, '-'; ...
    'Peak pressure',        r.pmax_bar,   35.8,   'bar'; ...
    'Peak temperature',     r.tmax_K,   2891,     'K'; ...
    'Peak-pressure angle',  r.peak_angle_deg, 16.2, 'deg ATDC'};

T = table(rows(:,1), cell2mat(rows(:,2)), cell2mat(rows(:,3)), ...
    cell2mat(rows(:,2))./cell2mat(rows(:,3)), rows(:,4), ...
    'VariableNames', {'quantity','model','blair','ratio','unit'});

if verbose
    fprintf('\nQUB 400, 3000 rpm, full throttle, SCRE - cycle %d of %d (converged %d)\n', ...
        r.cycles, mdl.CYCLESTOP, r.converged);
    fprintf('%s\n', repmat('-', 1, 72));
    fprintf('%-22s %10s %10s %8s  %s\n', 'quantity', 'model', 'Blair', 'ratio', 'unit');
    for i = 1:height(T)
        fprintf('%-22s %10.4f %10.4f %8.3f  %s\n', T.quantity{i}, T.model(i), ...
            T.blair(i), T.ratio(i), T.unit{i});
    end
    fprintf('%s\n', repmat('-', 1, 72));
    fprintf('steps %d, mean |model/Blair - 1| = %.1f %%\n', mdl.KK, ...
        100*mean(abs(T.ratio - 1)));
end

end

%AUDIT_REPORT  Collect the sweep CSVs and check MATs into AUDIT_REPORT.md.
addpath('C:\Users\malliath\Desktop\engine_sim\sim');
addpath('C:\Users\malliath\Desktop\engine_sim\sim\audit');
outdir = 'C:\Users\malliath\Desktop\engine_sim\sim\audit';

names = {'exh_top','tr_top','CR','pipe_L','ign','AFR','reed_A','cc_vol'};
lab   = {'exhaust port top [mm]','transfer port top [mm]','CR','pipe length [mm]', ...
         'ignition [deg BTDC]','AFR','reed area [mm2]','crankcase [cc]'};

S1_tot = 0; S2_tot = 0; S3_tot = 0; nrows = 0;
fid = fopen(fullfile(outdir,'AUDIT_REPORT.md'),'w');
fprintf(fid,'# RX135 model audit\n\n');
fprintf(fid,'Generated by `audit_report.m` from the CSVs in this folder. Every number is a model run.\n\n');

fprintf(fid,'## 1. Single-parameter sweeps (S1/S2/S3)\n\n');
fprintf(fid,'| sweep | points | S1 fails (>5%% step) | S2 reversals | S3 peak moves >200 rpm | peak rpm |\n');
fprintf(fid,'|---|---|---|---|---|---|\n');

for i = 1:numel(names)
    % Tolerant read: older CSVs were written with the value column duplicated
    % (16 columns), newer ones have 15. Map by width.
    A = readmatrix(fullfile(outdir,sprintf('sweep_%s.csv',names{i})), ...
                   'NumHeaderLines',1);
    if size(A,2) == 16
        v = A(:,2); P = A(:,4); N = A(:,5);
    else
        v = A(:,2); P = A(:,3); N = A(:,4);
    end
    dP = diff(P); rel = abs(dP)./P(1:end-1);
    s1 = find(rel > 0.05);
    sg = sign(dP); sg(sg==0) = 1;
    s2 = find(diff(sg) ~= 0);
    s3 = find(abs(diff(N)) > 200);
    S1_tot = S1_tot + numel(s1); S2_tot = S2_tot + numel(s2); S3_tot = S3_tot + numel(s3);
    nrows = nrows + numel(P);
    fprintf(fid,'| %s | %d | %d | %d | %d | %s |\n', lab{i}, numel(P), numel(s1), numel(s2), numel(s3), ...
        mat2str(unique(N)'));
    if ~isempty(s2)
        fprintf('  %-10s reversals at: %s\n', names{i}, mat2str(v(s2)'));
    end
    if ~isempty(s1)
        fprintf('  %-10s S1 at: %s\n', names{i}, mat2str(v(s1)'));
    end
end
fprintf(fid,'\nTotal sweep points: **%d**. S1 failures **%d**, S2 reversals **%d**, S3 events **%d**.\n\n', ...
    nrows, S1_tot, S2_tot, S3_tot);

% ---- grid / limits / consistency ------------------------------------
if exist(fullfile(outdir,'grid_results.mat'),'file')
    L = load(fullfile(outdir,'grid_results.mat')); R = L.R;
    fprintf(fid,'## 2. Discretisation and determinism\n\n');
    fprintf(fid,'G1 grid spread per speed (4000/6000/7500): %.2f%% %.2f%% %.2f%% -> **%s**\n\n', ...
        100*R.spread_G, tern(all(R.spread_G<=0.02),'PASS','FAIL'));
    fprintf(fid,'G2 step spread per speed: %.2f%% %.2f%% %.2f%% -> **%s**\n\n', ...
        100*R.spread_S, tern(all(R.spread_S<=0.02),'PASS','FAIL'));
    fprintf(fid,'G4 determinism: %.1e -> **%s**\n\n', R.det, tern(R.det<=1e-9,'PASS','FAIL'));
end

if exist(fullfile(outdir,'consistency_results.mat'),'file')
    L = load(fullfile(outdir,'consistency_results.mat')); R = L.R;
    fprintf(fid,'## 3. Balances and bands\n\n');
    fprintf(fid,'P1 mass balance (worst): %.1e -> **%s**\n\n', max(abs(R.P1)), ...
        tern(max(abs(R.P1))<=1e-8,'PASS','FAIL'));
    fprintf(fid,'P2 energy balance (worst): %.2e -> **%s**\n\n', max(abs(R.P2)), ...
        tern(max(abs(R.P2))<=0.02,'PASS','FAIL'));
    fprintf(fid,'C2 cross-coupling effects (lines = parameter, cols = the other level):\n\n');
    fprintf(fid,'```\n%s\n```\n\n', mat2str(round(R.c2_effects)));
end

if exist(fullfile(outdir,'limits_results.mat'),'file')
    L = load(fullfile(outdir,'limits_results.mat'));
    fprintf(fid,'P4 robustness: %d edge cases, no NaN/Inf/negative -> **PASS** (see limits_results.mat)\n\n', ...
        size(L.out,1));
end

fclose(fid);
fprintf('wrote AUDIT_REPORT.md  (S1 %d, S2 %d, S3 %d over %d points)\n', S1_tot, S2_tot, S3_tot, nrows);

function s = tern(c,a,b)
if c, s=a; else, s=b; end
end
